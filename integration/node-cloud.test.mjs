test('node status distinguishes assignment, recency and invalid timestamps',()=>{
  const now=Date.now();const t={device:{device_id:'a'},latest:{timestamp:new Date(now).toISOString()}};
  assert.equal(readingStatus(null,false,'',now),'No assigned node');
  assert.equal(readingStatus({...t,latest:null},false,'',now),'Waiting for first reading');
  assert.equal(readingStatus(t,false,'',now),'Recent data');
  assert.equal(readingStatus(t,false,'',now+600001),'No recent data');
  assert.equal(readingStatus({...t,latest:{timestamp:'bad'}},false,'',now),'Invalid reading time');
  assert.equal(readingStatus(t,false,'Offline',now),'Unable to check node');
});

test('node storage registration preserves an existing owner and restricts raw table access',async()=>{
  const result=await rpc('register_allert_node_storage',['ALLERT-NODE-003','sensor_readings_node3']);
  assert.equal(result.ok,true);
  assert.equal((await db.query("SELECT user_id FROM sensor_devices WHERE device_id='ALLERT-NODE-001'")).rows[0].user_id,other);
  for(const role of ['anon','authenticated'])assert.equal((await db.query("SELECT has_table_privilege($1,'public.sensor_readings_node3','SELECT') AS access",[role])).rows[0].access,false);
  await assert.rejects(rpc('register_allert_node_storage',['ALLERT-NODE-003','sensor_readings;DROP TABLE sensor_devices']),/Invalid/);
});

